CREATE TABLE app_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(80) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    role VARCHAR(40) NOT NULL DEFAULT 'ADMIN',
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE clubs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    official_name VARCHAR(150) NOT NULL,
    short_name VARCHAR(80),
    acronym VARCHAR(12) UNIQUE,
    description VARCHAR(2000),
    founded_year INTEGER,
    country VARCHAR(80),
    department VARCHAR(100),
    province VARCHAR(100),
    district VARCHAR(100),
    stadium VARCHAR(150),
    president VARCHAR(120),
    delegate_name VARCHAR(120),
    phone VARCHAR(40),
    email VARCHAR(180),
    website VARCHAR(255),
    primary_color VARCHAR(7),
    secondary_color VARCHAR(7),
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_clubs_status CHECK (status IN ('ACTIVE', 'INACTIVE')),
    CONSTRAINT ck_clubs_founded_year CHECK (founded_year IS NULL OR founded_year BETWEEN 1800 AND 2100)
);

CREATE INDEX ix_clubs_status_name ON clubs (status, official_name);

CREATE TABLE audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor VARCHAR(80) NOT NULL,
    action VARCHAR(80) NOT NULL,
    entity_type VARCHAR(80) NOT NULL,
    entity_id BIGINT NOT NULL,
    details VARCHAR(2000),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX ix_audit_log_entity ON audit_log (entity_type, entity_id, created_at DESC);
