CREATE TABLE match_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id BIGINT NOT NULL,
    team_id BIGINT NOT NULL,
    player_id BIGINT NOT NULL,
    related_player_id BIGINT,
    event_minute INTEGER NOT NULL,
    event_type VARCHAR(20) NOT NULL,
    notes VARCHAR(500),
    CONSTRAINT fk_match_events_match FOREIGN KEY (match_id) REFERENCES matches(id) ON DELETE RESTRICT,
    CONSTRAINT fk_match_events_team FOREIGN KEY (team_id) REFERENCES teams(id) ON DELETE RESTRICT,
    CONSTRAINT fk_match_events_player FOREIGN KEY (player_id) REFERENCES players(id) ON DELETE RESTRICT,
    CONSTRAINT fk_match_events_related_player FOREIGN KEY (related_player_id) REFERENCES players(id) ON DELETE RESTRICT,
    CONSTRAINT ck_match_event_minute CHECK (event_minute BETWEEN 0 AND 150),
    CONSTRAINT ck_match_event_type CHECK (event_type IN ('GOAL', 'OWN_GOAL', 'ASSIST', 'YELLOW_CARD', 'RED_CARD', 'SUBSTITUTION')),
    CONSTRAINT ck_match_event_related CHECK (
        (event_type = 'SUBSTITUTION' AND related_player_id IS NOT NULL AND related_player_id <> player_id)
        OR (event_type <> 'SUBSTITUTION' AND related_player_id IS NULL)
    )
);

CREATE INDEX ix_match_events_match_minute ON match_events (match_id, event_minute);
CREATE INDEX ix_match_events_player_type ON match_events (player_id, event_type);
